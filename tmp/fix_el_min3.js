const fixed = d.map((t) => {
  let el = t.el.slice();
  const add = FILL[t.w] || [];
  add.forEach((e) => { if (el.indexOf(e) < 0 && el.length < 5) el.push(e); });
  // 有效性过滤：必须在 ELEMENT 字典内
  el = el.filter((e) => { const p = e.split(':'); return LIB.ELEMENT[p[0]] && LIB.ELEMENT[p[0]][p[1]]; });
  const dedup = [];
  el.forEach((e) => { if (dedup.indexOf(e) < 0) dedup.push(e); });
  dedup.sort((a, b) => ORDER.indexOf(a.split(':')[0]) - ORDER.indexOf(b.split(':')[0]));
  return Object.assign({}, t, { el: dedup });
});

