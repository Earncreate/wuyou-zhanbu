// x 取值依该事物所临六亲/万物类象五行（与 diet/wealth 同构）：子孙火2、父母木1、妻财土5、官鬼水4、兄弟木1。
const fs = require('fs');
const path = require('path');
const G9 = { 1: 1, 2: 3, 3: 2, 4: 4, 5: 10 };
const G10 = { 1: 1, 2: 1, 3: 3, 4: 2, 5: 6 };
const G3 = { 1: 6, 2: 5, 3: 7, 4: 2, 5: 1 };
const ORDER = ['g1', 'g2', 'g3', 'g4', 'g5', 'g6', 'g7', 'g8', 'g9', 'g10'];

function padEl(el, x) {
  const set = new Map();
  (el || []).forEach((e) => { const i = e.indexOf(':'); set.set(e.slice(0, i), e.slice(i + 1)); });
  if (!set.has('g9')) set.set('g9', G9[x] || 2);
  if (!set.has('g10')) set.set('g10', G10[x] || 6);
  if (set.size < 3 && !set.has('g3')) set.set('g3', G3[x] || 7);
  if (set.size < 3 && !set.has('g1')) set.set('g1', 1);
  return ORDER.filter((g) => set.has(g)).map((g) => g + ':' + set.get(g));
}

// 元组：[w, l1, l2, x, note, m?]  m=[mat,form,state,mot] 或省略(null)
function build(modId, L1, L2, raw, category) {
  const terms = raw.map((t) => {
    const [w, l1, l2, x, note, m] = t;
    return { w, l1, l2, x, el: padEl([], x), note, m: m ? { mat: m[0], form: m[1], state: m[2], mot: m[3] } : { mat: null, form: null, state: 1, mot: null } };
  });
  const obj = { L1, L2, terms, category };
  const out = '// 模块 ' + modId + ' 自动生成词表（≥64 类，el 按五行补至 ≥3）。\nmodule.exports = ' + JSON.stringify(obj, null, 2) + ';\n';
  fs.writeFileSync(path.join(__dirname, modId + '64.js'), out);
  return terms.length;
}

